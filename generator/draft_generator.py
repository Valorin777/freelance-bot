"""Модуль 3: генерация черновиков откликов через Claude API."""

import logging

import anthropic
from anthropic import AsyncAnthropic

logger = logging.getLogger(__name__)

GENERATOR_SYSTEM = """\
Ты пишешь черновики откликов на фриланс-заказы от лица конкретного разработчика.
Пиши от первого лица, как будто пишет он сам.

Кто он:
- Фулстек-разработчик: Next.js, TypeScript, FastAPI, Firebase, Anthropic API (AI-интеграции)
- Два живых продакшн-проекта:
  - prolatelier.ru (AI-подбор рецептов, PWA: Next.js + FastAPI + Claude API)
  - faithof.ru (мультиязычный интернет-магазин)
- Делает быстро, показывает результат по этапам

ГЛАВНОЕ ТРЕБОВАНИЕ: текст не должен выглядеть сгенерированным нейросетью.
Заказчик должен прочитать его как обычное сообщение от живого разработчика
в телеграме. Любой признак ИИ-текста недопустим.

Правила текста:
- Обращение к заказчику строго на «Вы». При этом язык живой и разговорный,
  без канцелярита: вежливо, но не официозно.
- ЗАПРЕЩЕНО длинное тире «—» и двойной дефис «--». Вместо них запятая, точка,
  двоеточие или перестроенная фраза. Обычный дефис внутри слов и диапазонов
  («2-3 дня», «онлайн-запись») использовать можно.
- ЗАПРЕЩЕНЫ шаблонные ИИ-конструкции: «Здравствуйте! Я внимательно изучил ваш
  проект...», «Буду рад сотрудничеству», «Обладаю обширным опытом», «Готов
  приступить немедленно», «Выполню качественно и в срок» и всё похожее.
- ЗАПРЕЩЕНЫ и другие маркеры ИИ-текста: конструкции «не просто X, а Y», тройные
  перечисления («быстро, качественно, надёжно»), восторженные вводные
  («Отличная задача!»), эмодзи, заголовки, буллет-списки.
- Просто живой текст, 2-4 коротких абзаца, примерно 400-800 знаков. Предложения
  разной длины, как пишут люди: где-то короткое, где-то подлиннее.
- Отклик уникален под конкретный заказ: зацепись за 1-2 конкретные детали из
  текста заказа, покажи, что понял задачу. Если видишь подводный камень или
  важный уточняющий вопрос по делу, упомяни его.
- Портфолио упоминай только там, где оно реально в тему: prolatelier.ru если
  заказ про AI, ботов, интеграции API, PWA; faithof.ru если про магазины,
  каталоги, мультиязычность. Если ни один не в тему, просто назови стек, без ссылок.
- Не выдумывай опыт, которого нет в описании выше. Не называй цену и срок,
  максимум предложи обсудить.
- Закончи простым следующим шагом: вопрос по задаче или предложение списаться.

Отвечай ТОЛЬКО текстом отклика, без пояснений, без вариантов, без кавычек.
"""


def _strip_ai_markers(text: str) -> str:
    """Страховка: убирает длинные тире, даже если модель нарушила запрет."""
    text = text.replace(" — ", ", ").replace("— ", ", ").replace(" —", ",")
    text = text.replace("—", "-")
    text = text.replace(" – ", ", ").replace("–", "-")
    text = text.replace("--", "-")
    return text


class DraftGenerator:
    def __init__(self, client: AsyncAnthropic, model: str):
        self._client = client
        self._model = model

    async def generate(self, order_text: str, kind: str = "order") -> str | None:
        """Генерирует черновик отклика. Возвращает None при ошибке API."""
        if kind == "parttime":
            task = (
                "Это вакансия с проектной/частичной занятостью или подработкой. Напиши отклик как "
                "на такую вакансию: коротко и по делу отзовись, покажи релевантный опыт под задачу, "
                "уточни формат/загрузку если уместно. Не пиши «сделаю ваш проект под ключ» — речь про "
                "работу в команде/на проекте."
            )
        else:
            task = "Это разовый заказ от клиента. Напиши черновик отклика на заказ."
        try:
            response = await self._client.messages.create(
                model=self._model,
                # с запасом: токены adaptive thinking входят в этот же лимит
                max_tokens=8000,
                thinking={"type": "adaptive"},
                system=GENERATOR_SYSTEM,
                messages=[
                    {
                        "role": "user",
                        "content": f"Текст поста:\n\n{order_text}\n\n{task}",
                    }
                ],
            )
        except anthropic.RateLimitError:
            logger.warning("Claude API: превышен лимит запросов (генератор), заказ будет повторён")
            return None
        except anthropic.APIStatusError as e:
            logger.error("Claude API: ошибка %s при генерации: %s", e.status_code, e.message)
            return None
        except anthropic.APIConnectionError:
            logger.error("Claude API: сетевая ошибка при генерации")
            return None

        if response.stop_reason == "refusal":
            logger.warning("Claude отказался генерировать отклик для этого заказа")
            return None
        if response.stop_reason == "max_tokens":
            # обрезанный черновик хуже, чем никакой — заказ будет повторён
            logger.warning("Черновик обрезан по лимиту токенов, заказ будет повторён")
            return None

        draft = "".join(
            block.text for block in response.content if block.type == "text"
        ).strip()
        if not draft:
            return None
        return _strip_ai_markers(draft)
